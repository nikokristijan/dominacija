import { renderToStaticMarkup } from 'react-dom/server';
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { Penguin } from '../src/components/art/Penguin';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const moods = ['neutral', 'happy', 'celebrating', 'angry', 'thinking', 'surprised', 'defeated', 'confident'] as const;
const html = `<html><body style="margin:0;background:#EDE8FF;display:grid;grid-template-columns:repeat(4,220px);gap:8px;padding:12px">${moods.map((m) => `<div style="text-align:center;font:14px sans-serif">${renderToStaticMarkup(<Penguin mood={m} size={200} />)}<br>${m}</div>`).join('')}</body></html>`;
const out = process.argv[2];
(async () => { const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 960, height: 640 }, deviceScaleFactor: 1 }); await p.setContent(html); await p.screenshot({ path: out }); await b.close(); })();
